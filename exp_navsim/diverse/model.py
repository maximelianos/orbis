"""Intent-factorized flow matching: a trajectory distribution that cannot collapse across intentions.

    future = CV(v_hat) + a_k + e

    v_hat   ego velocity and acceleration regressed from the image features (kinematic head);
            CV(v_hat) is the constant-velocity rollout over the 8 future poses (2 Hz)
    a_k     anchor k of M: k-means centre of the training residuals future - CV(v) (anchors.py),
            chosen by the intent head p(k | scene)
    e       residual inside the cell of anchor k, generated by flow matching conditioned on
            the image tokens, the v_hat token and an embedding of k

The logged ego status is a regression target only; the inputs are image features (and
optionally the driving command). With use_kin=False CV is zero, with anchors=None there
is one zero anchor, and both off is the plain probe of models/probe.py.

Training uses the hard nearest anchor k* of the logged future, so the flow of anchor k
only ever sees residuals of its own Voronoi cell: whatever the flow memorizes, a sample
drawn for anchor k stays near anchor k. Spread between intentions comes from which
anchors are sampled (sample(..., mode="prop" | "strat")).
"""

import torch
import torch.nn as nn
import torch.nn.functional as F

from exp_navsim.diverse.controls import ControlCodec, from_controls, speed_of, to_controls
from exp_navsim.models.codec import PolyCodec
from exp_navsim.models.denoiser import ProbeDenoiser
from networks.blocks import ContextTransformer

DT = 0.5                                      # s between future poses
STEPS = torch.arange(1, 9, dtype=torch.float32) * DT


def constant_velocity(v):
    """v (B, >=2) ego-frame velocity -> (B, 8, 3) poses, heading 0."""
    xy = STEPS.to(v.device)[None, :, None] * v[:, None, :2]
    return torch.cat([xy, torch.zeros_like(xy[..., :1])], dim=-1)


def anchor_distance(resid, anchors):
    """ADE between residuals (B, 8, >=2) and anchors (M, 8, >=2) -> (B, M)."""
    return (resid[:, None, :, :2] - anchors[None, :, :, :2]).norm(dim=-1).mean(-1)


class IntentFlow(nn.Module):
    def __init__(self, in_channels, num_frames, anchors=None, use_kin=True, use_command=False, hidden_dim=64,
                 image_tokens=16, ff_dim=128, num_heads=4, depth=4, poly_order=3, sigma_min=1e-5, tau=1.0,
                 codec=None):
        super().__init__()
        D = hidden_dim
        self.use_kin, self.sigma_min, self.tau = use_kin, sigma_min, tau
        anchors = torch.zeros(1, 8, 3) if anchors is None else torch.as_tensor(anchors, dtype=torch.float32)
        self.register_buffer("anchors", anchors)
        self.num_anchors = len(anchors)
        self.register_buffer("status_mean", torch.zeros(4))
        self.register_buffer("status_std", torch.ones(4))

        self.codec = PolyCodec(poly_order) if codec is None else codec
        self.denoiser = ProbeDenoiser(self.codec.latent_dim, in_channels, num_frames, D, image_tokens, ff_dim,
                                      num_heads, depth, use_status=False, use_command=use_command)
        # Two read-out queries over the condition tokens: kinematics and intent.
        self.readout_query = nn.Parameter(torch.randn(1, 2, D) * 0.02)
        self.readout = ContextTransformer(D, ff_dim, num_heads, 0.0, adaln=False)
        self.kin_head = nn.Linear(D, 4)
        self.kin_token = nn.Sequential(nn.Linear(4, D), nn.GELU(), nn.Linear(D, D))
        self.intent_head = nn.Linear(D, self.num_anchors)
        self.anchor_emb = nn.Embedding(self.num_anchors, D)

    # ------------------------------------------------------------------ fit -- #
    @torch.no_grad()
    def fit(self, future, status):
        """Status and codec statistics from the training futures (B, 8, 3) and status (B, 4)."""
        self.status_mean.copy_(status.mean(0))
        self.status_std.copy_(status.std(0).clamp(min=1e-3))
        resid = future - (constant_velocity(status) if self.use_kin else 0)
        k = anchor_distance(resid, self.anchors).argmin(1)
        return self.codec.fit(resid - self.anchors[k])

    def nearest_anchor(self, future, status):
        """Anchor distances (B, M) and the nearest anchor (B,) of logged futures."""
        dist = anchor_distance(future - (constant_velocity(status) if self.use_kin else 0), self.anchors)
        return dist, dist.argmin(1)

    # -------------------------------------------------------------- forward -- #
    def encode_scene(self, batch):
        """-> base condition tokens (B, L, D), kinematics (B, 4) in m/s units or None, intent logits (B, M)."""
        base = self.denoiser.condition(batch)
        r = self.readout(base, self.readout_query.expand(len(base), -1, -1))
        kin = self.kin_head(r[:, 0]) * self.status_std + self.status_mean if self.use_kin else None
        return base, kin, self.intent_head(r[:, 1])

    def flow_condition(self, base, kin, k):
        tokens = [base, self.anchor_emb(k)[:, None]]
        if kin is not None:
            tokens.append(self.kin_token((kin.detach() - self.status_mean) / self.status_std)[:, None])
        return torch.cat(tokens, dim=1)

    def prior(self, kin, k):
        cv = constant_velocity(kin.detach()) if kin is not None else 0
        return cv + self.anchors[k]

    def target(self, future, status, kin, k):
        """What the flow generates (before the codec) for a logged future."""
        return future - self.prior(kin, k)

    def decode(self, x, kin, k):
        """Inverse of target: flow output x (after the codec) -> futures (B, 8, 3)."""
        return x + self.prior(kin, k)

    def loss(self, batch, t=None, noise=None):
        future, status = batch["future"], batch["status"]
        base, kin, logits = self.encode_scene(batch)
        logs = {}
        dist, k = self.nearest_anchor(future, status)                          # (B, M), (B,)

        z = self.codec.encode(self.target(future, status, kin, k))
        t = torch.rand(len(z), device=z.device) if t is None else t
        noise = torch.randn_like(z) if noise is None else noise
        s = self.sigma_min
        z_t = (1 - t[:, None]) * z + (s + t[:, None] * (1 - s)) * noise
        pred = self.denoiser(self.flow_condition(base, kin, k), z_t, t)
        loss = logs["fm"] = ((pred - (z - (1 - s) * noise)) ** 2).mean()
        if self.use_kin:
            logs["kin"] = (((kin - status) / self.status_std) ** 2).mean()
            loss = loss + logs["kin"]
        if self.num_anchors > 1:
            target = F.softmax(-dist / self.tau, dim=1)
            logs["intent"] = -(target * F.log_softmax(logits, 1)).sum(1).mean()
            loss = loss + logs["intent"]
        return loss, logs

    # ------------------------------------------------------------- sampling -- #
    @torch.no_grad()
    def choose_anchors(self, logits, num_samples, mode="prop", top=8, generator=None):
        """-> (K, B) anchor indices. prop: k ~ p(k | scene); nucleus<p>: k ~ p(k | scene) restricted to
        the most likely anchors with total mass p (top-p sampling); strat: the K samples split over the top anchors."""
        K, (B, M) = num_samples, logits.shape
        if M == 1:
            return torch.zeros(K, B, dtype=torch.long, device=logits.device)
        if mode == "prop":
            return torch.multinomial(F.softmax(logits, 1), K, replacement=True, generator=generator).T
        if mode.startswith("nucleus"):                                         # e.g. nucleus0.8
            p, order = F.softmax(logits, 1).sort(1, descending=True)
            keep = p.cumsum(1) - p < float(mode[len("nucleus"):])               # smallest set with mass >= top_p
            p = torch.zeros_like(p).scatter(1, order, p * keep)
            return torch.multinomial(p, K, replacement=True, generator=generator).T
        if mode == "strat":
            topk = logits.topk(min(top, M), dim=1).indices                     # (B, top)
            return topk[:, torch.arange(K, device=logits.device) % topk.shape[1]].T
        raise ValueError(mode)

    @torch.no_grad()
    def sample(self, batch, num_samples, steps=20, mode="prop", top=8, generator=None):
        """-> futures (K, B, 8, 3), anchors (K, B), kinematics (B, 4) or None, intent logits (B, M)."""
        base, kin, logits = self.encode_scene(batch)
        ks = self.choose_anchors(logits, num_samples, mode, top, generator)
        K, B = ks.shape
        k = ks.flatten()                                                       # sample-major
        base_k = base.repeat(K, 1, 1)
        kin_k = kin.repeat(K, 1) if kin is not None else None
        cond = self.flow_condition(base_k, kin_k, k)
        z = torch.randn(K * B, self.codec.latent_dim, device=base.device, generator=generator)
        ts = torch.linspace(1, 0, steps + 1, device=base.device)
        for i in range(steps):
            z = z + self.denoiser(cond, z, ts[i].expand(K * B)) * (ts[i] - ts[i + 1])
        future = self.decode(self.codec.decode(z), kin_k, k)
        return future.unflatten(0, (K, B)), ks, kin, logits


class CtrlFlow(IntentFlow):
    """IntentFlow in control space (controls.py): anchors are control sequences (M, 8, 2) of
    acceleration and yaw rate, the flow generates the control residual to the anchor, and
    the future is the unicycle roll-out from the regressed speed. Intent targets and the
    nearest anchor are measured in pose space, with the anchors rolled out from the logged
    speed, so an anchor means the same manoeuvre at every speed."""

    def __init__(self, in_channels, num_frames, anchors=None, ctrl_order=8, **kw):
        anchors = torch.zeros(1, 8, 2) if anchors is None else anchors
        kw["use_kin"] = True
        super().__init__(in_channels, num_frames, anchors, codec=ControlCodec(ctrl_order), **kw)

    def anchor_poses(self, v0):
        """(B,) speeds -> (B, M, 8, 3) anchor roll-outs."""
        return from_controls(self.anchors[None].expand(len(v0), -1, -1, -1), v0[:, None].expand(-1, self.num_anchors))

    def nearest_anchor(self, future, status):
        dist = (future[:, None, :, :2] - self.anchor_poses(speed_of(status))[..., :2]).norm(dim=-1).mean(-1)
        return dist, dist.argmin(1)

    @torch.no_grad()
    def fit(self, future, status):
        self.status_mean.copy_(status.mean(0))
        self.status_std.copy_(status.std(0).clamp(min=1e-3))
        k = torch.cat([self.nearest_anchor(future[i:i + 4096], status[i:i + 4096])[1]
                       for i in range(0, len(future), 4096)])
        rec = from_controls(to_controls(future, speed_of(status)), speed_of(status))
        out = self.codec.fit(to_controls(future, speed_of(status)) - self.anchors[k])
        out["unicycle_ade"] = (rec[..., :2] - future[..., :2]).norm(dim=-1).mean().item()
        return out

    def target(self, future, status, kin, k):
        return to_controls(future, speed_of(status)) - self.anchors[k]

    def decode(self, x, kin, k):
        return from_controls(x + self.anchors[k], speed_of(kin))


class VocabDist(IntentFlow):
    """Categorical distribution over a vocabulary of V logged trajectories (VADv2,
    arXiv 2402.13243): p(v | scene) = softmax(<q(scene), phi(traj_v)> / sqrt(D) + b_v).
    phi embeds the trajectory geometry, so close trajectories get close logits. Trained
    with the soft cross-entropy against softmax(-ADE(traj_v, future) / tau). A sample is a
    vocabulary entry: every candidate is a trajectory that a human drove."""

    def __init__(self, in_channels, num_frames, vocab, **kw):
        kw["use_kin"] = False
        super().__init__(in_channels, num_frames, vocab, **kw)
        D = kw.get("hidden_dim", 64)
        flat = self.anchors[..., :2].flatten(1)
        self.register_buffer("vocab_mean", flat.mean(0))
        self.register_buffer("vocab_std", flat.std(0).clamp(min=1e-3))
        self.traj_emb = nn.Sequential(nn.Linear(16, 2 * D), nn.GELU(), nn.Linear(2 * D, D))
        self.vocab_bias = nn.Parameter(torch.zeros(self.num_anchors))
        self.intent_head = None

    @torch.no_grad()
    def fit(self, future, status):
        self.status_mean.copy_(status.mean(0))
        self.status_std.copy_(status.std(0).clamp(min=1e-3))
        d = torch.cat([self.nearest_anchor(future[i:i + 512], status[i:i + 512])[0].min(1).values
                       for i in range(0, len(future), 512)])
        return {"vocab_oracle_ade": d.mean().item()}

    def encode_scene(self, batch):
        base = self.denoiser.condition(batch)
        q = self.readout(base, self.readout_query.expand(len(base), -1, -1))[:, 1]
        phi = self.traj_emb((self.anchors[..., :2].flatten(1) - self.vocab_mean) / self.vocab_std)
        return base, None, q @ phi.T / q.shape[-1] ** 0.5 + self.vocab_bias

    def loss(self, batch, t=None, noise=None):
        _, _, logits = self.encode_scene(batch)
        dist, _ = self.nearest_anchor(batch["future"], batch["status"])
        loss = -(F.softmax(-dist / self.tau, 1) * F.log_softmax(logits, 1)).sum(1).mean()
        return loss, {"intent": loss}

    @torch.no_grad()
    def sample(self, batch, num_samples, steps=20, mode="prop", top=8, generator=None):
        _, _, logits = self.encode_scene(batch)
        ks = self.choose_anchors(logits, num_samples, mode, top, generator)
        return self.anchors[ks], ks, None, logits


def farthest_point_vocab(future, num, seed=0):
    """VADv2's planning vocabulary: farthest-point sampling (ADE) over logged futures (N, 8, 3) -> (num, 8, 3)."""
    xy = future[..., :2].flatten(1)
    g = torch.Generator(device=future.device).manual_seed(seed)
    idx = [torch.randint(len(xy), (1,), generator=g, device=future.device).item()]
    d = torch.full((len(xy),), float("inf"), device=future.device)
    for _ in range(num - 1):
        d = torch.minimum(d, (xy.view(-1, 8, 2) - xy[idx[-1]].view(8, 2)).norm(dim=-1).mean(-1))
        idx.append(d.argmax().item())
    return future[idx]


class CtrlVocab(CtrlFlow):
    """VocabDist in control space: a categorical over V logged control sequences
    (acceleration, yaw rate), each rolled out from the regressed speed. A sample is a
    manoeuvre a human drove, started at the current speed of this car. No flow."""

    def __init__(self, in_channels, num_frames, vocab, **kw):
        super().__init__(in_channels, num_frames, vocab, **kw)
        D = kw.get("hidden_dim", 64)
        flat = self.anchors.flatten(1)
        self.register_buffer("vocab_mean", flat.mean(0))
        self.register_buffer("vocab_std", flat.std(0).clamp(min=1e-3))
        self.traj_emb = nn.Sequential(nn.Linear(16, 2 * D), nn.GELU(), nn.Linear(2 * D, D))
        self.vocab_bias = nn.Parameter(torch.zeros(self.num_anchors))
        self.intent_head = None

    @torch.no_grad()
    def fit(self, future, status):
        self.status_mean.copy_(status.mean(0))
        self.status_std.copy_(status.std(0).clamp(min=1e-3))
        d = torch.cat([self.nearest_anchor(future[i:i + 512], status[i:i + 512])[0].min(1).values
                       for i in range(0, len(future), 512)])
        return {"vocab_oracle_ade": d.mean().item()}

    def encode_scene(self, batch):
        base = self.denoiser.condition(batch)
        r = self.readout(base, self.readout_query.expand(len(base), -1, -1))
        kin = self.kin_head(r[:, 0]) * self.status_std + self.status_mean
        phi = self.traj_emb((self.anchors.flatten(1) - self.vocab_mean) / self.vocab_std)
        return base, kin, r[:, 1] @ phi.T / r.shape[-1] ** 0.5 + self.vocab_bias

    def loss(self, batch, t=None, noise=None):
        _, kin, logits = self.encode_scene(batch)
        dist, _ = self.nearest_anchor(batch["future"], batch["status"])
        logs = {"intent": -(F.softmax(-dist / self.tau, 1) * F.log_softmax(logits, 1)).sum(1).mean(),
                "kin": (((kin - batch["status"]) / self.status_std) ** 2).mean()}
        return logs["intent"] + logs["kin"], logs

    @torch.no_grad()
    def sample(self, batch, num_samples, steps=20, mode="prop", top=8, generator=None):
        _, kin, logits = self.encode_scene(batch)
        ks = self.choose_anchors(logits, num_samples, mode, top, generator)
        v0 = speed_of(kin)[None].expand(len(ks), -1)
        return from_controls(self.anchors[ks], v0), ks, kin, logits
